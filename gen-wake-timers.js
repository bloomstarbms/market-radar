// Generates wake-timers.ps1 from data/macro-calendar.json: one Task Scheduler wake
// timer 15 minutes before every FULL-tier stage (CPI/FOMC), so the machine is awake
// when the stage fires. $0 answer to the measured miss (Aug 12 CPI: machine slept
// 22:11Z -> 13:11Z through T-60m, the pre-print snapshot, T+5m and T+30m).
//
// Wake timers wake from sleep/hibernate, NOT from shutdown — verified applicable:
// event log shows every long gap since Aug 2 was Modern Standby sleep, and the
// RTCWAKE policy is Enabled on AC. Times are emitted in UTC; PowerShell converts to
// machine-local at task creation, so this file is timezone-safe by construction.
// RERUN whenever the calendar changes: node gen-wake-timers.js, then SETUP-WAKE-TIMERS.bat.
import { readFileSync, writeFileSync } from 'node:fs';

function etToUtc(dateStr, hm) {
  for (const off of [4, 5]) {
    const cand = Date.parse(`${dateStr}T${hm}:00-0${off}:00`);
    const back = new Intl.DateTimeFormat('en-US', { timeZone: 'America/New_York', hour12: false, hour: '2-digit', minute: '2-digit' }).format(new Date(cand));
    if (back === hm) return cand;
  }
  return Date.parse(`${dateStr}T${hm}:00-05:00`);
}
const STAGE_AT = { t24h: -24 * 3600e3, t60m: -3600e3, t5m: 5 * 60e3, t30m: 30 * 60e3 };
// Tier -> stages mirrors macro.js STAGES. ANY tier promotion in the calendar is also
// a wake-timer regeneration — rerun this + SETUP-WAKE-TIMERS.bat after every edit.
const TIER_STAGES = { FULL: ['t24h', 't60m', 't5m', 't30m'], STANDARD: ['t24h', 't5m'] };
const WAKE_EARLY = 15 * 60e3;

const cal = JSON.parse(readFileSync('data/macro-calendar.json', 'utf8')).events;
const wakes = [];
for (const ev of cal) {
  const stages = TIER_STAGES[ev.tier];
  if (!stages) continue;
  const t0 = etToUtc(ev.date, ev.et);
  for (const stage of stages) {
    const at = t0 + STAGE_AT[stage] - WAKE_EARLY;
    if (at > Date.now()) wakes.push({ name: `${ev.id}-${stage}`, utc: new Date(at).toISOString().slice(0, 19) + 'Z' });
  }
}

const ps = `# GENERATED by gen-wake-timers.js — do not hand-edit; rerun the generator.
$ErrorActionPreference = 'Continue'
# Best effort: enable wake timers on battery too (AC already Enabled; may need admin)
powercfg /setdcvalueindex SCHEME_CURRENT SUB_SLEEP RTCWAKE 1
powercfg /setactive SCHEME_CURRENT
# Replace any previous set atomically
Get-ScheduledTask -TaskPath '\\MarketRadar\\' -ErrorAction SilentlyContinue | Unregister-ScheduledTask -Confirm:$false
$action = New-ScheduledTaskAction -Execute 'cmd.exe' -Argument '/c exit'
$settings = New-ScheduledTaskSettingsSet -WakeToRun -StartWhenAvailable -ExecutionTimeLimit (New-TimeSpan -Minutes 5)
$wakes = @(
${wakes.map((w) => `  @('${w.name}', '${w.utc}')`).join(',\n')}
)
foreach ($w in $wakes) {
  $local = ([datetime]::Parse($w[1], $null, [System.Globalization.DateTimeStyles]::AdjustToUniversal)).ToLocalTime()
  $trigger = New-ScheduledTaskTrigger -Once -At $local
  Register-ScheduledTask -TaskName ('Wake-' + $w[0]) -TaskPath '\\MarketRadar\\' -Action $action -Trigger $trigger -Settings $settings -Force | Out-Null
  Write-Output ('created Wake-' + $w[0] + '  utc=' + $w[1] + '  local=' + $local.ToString('yyyy-MM-dd HH:mm'))
}
Write-Output ('TOTAL: ' + (Get-ScheduledTask -TaskPath '\\MarketRadar\\').Count + ' wake timers registered')
`;
writeFileSync('wake-timers.ps1', ps);
console.log(`wake-timers.ps1 written: ${wakes.length} wake timers (FULL + STANDARD stages, T-15m each)`);
